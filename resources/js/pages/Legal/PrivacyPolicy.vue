      collect and verify identification information about Instructors who earn money through the Platform, and
      to report that information together with their earnings annually to HMRC.
    </p>
    <p>The information we report includes:</p>
    <ul>
      <li>Instructor identifying information (name, primary address, date of birth, National Insurance Number, Unique Taxpayer Reference and VAT Registration Number where held, jurisdiction(s) of residence);</li>
      <li>bank account information used for payouts;</li>
      <li>totals of fees, payouts and platform earnings per quarter.</li>
    </ul>
    <p>
      Our lawful basis for this processing is <strong>legal obligation</strong>. We cannot delete this data on request
      while the reporting obligation applies. Before each annual submission to HMRC we will provide affected
      Instructors with a copy of the information we report about them.
    </p>

    <h2>11. Making Tax Digital and HMRC fraud-prevention data</h2>
    <p>
